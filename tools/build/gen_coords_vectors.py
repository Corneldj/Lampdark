#!/usr/bin/env python3
"""Writes native/tests/golden/coords_vectors.json and coords_vectors.gen.h (FND-07).

Shared test vectors for cell/local division and ring lookup, checked by doctest and GUT.
Rings are computed exactly (doubled integers) and cross-checked against float sqrt.
Usage: python3 tools/build/gen_coords_vectors.py [--check]
"""
import json
import math
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parents[2]
OUT_JSON = GAME / "native/tests/golden/coords_vectors.json"
OUT_H = GAME / "native/tests/golden/coords_vectors.gen.h"
CELL = 20
SHAFT2 = (20, 20)  # (10.0, 10.0) doubled
BOUNDS = [80, 200, 400, 700]


def ring_exact(x, y, bounds=BOUNDS):
    dx = 2 * x + 1 - SHAFT2[0]
    dy = 2 * y + 1 - SHAFT2[1]
    d2 = dx * dx + dy * dy
    return sum(1 for b in bounds if d2 >= (2 * b) ** 2)


def ring_float(px, py, bounds=BOUNDS):
    d = math.hypot(px - SHAFT2[0] / 2, py - SHAFT2[1] / 2)
    return sum(1 for b in bounds if d >= b)


def tiles_at(half_dx, half_dy):
    """The 8 symmetric tiles whose centres are (±dx, ±dy) and (±dy, ±dx) from the shaft,
    with dx, dy given as doubled offsets (odd integers)."""
    out = set()
    for a, b in ((half_dx, half_dy), (half_dy, half_dx)):
        for sa in (1, -1):
            for sb in (1, -1):
                ex, ey = sa * a, sb * b  # doubled offsets
                x = (ex + SHAFT2[0] - 1) // 2
                y = (ey + SHAFT2[1] - 1) // 2
                out.add((x, y))
    return sorted(out)


def build():
    div = []
    for t in [-41, -40, -39, -21, -20, -19, -1, 0, 1, 19, 20, 21, 39, 40, 199, -200]:
        div.append({"tile": t, "cell": t // CELL, "local": t % CELL})
    rings = []
    for distance in [79.5, 80.5, 199.5, 200.5, 399.5, 400.5, 699.5, 700.5, 10000.0]:
        expected = sum(1 for b in BOUNDS if distance >= b)
        # Axis: centre (distance, 0.5) doubled -> (2*distance, 1).
        axis = (int(round(2 * distance)) | 1, 1)
        # Diagonal: the odd doubled offset nearest distance/sqrt(2), on the same side of the bound.
        c = 2 * distance / math.sqrt(2)
        candidates = sorted({int(math.floor(c)) | 1, (int(math.floor(c)) | 1) - 2, (int(math.floor(c)) | 1) + 2},
                            key=lambda o: abs(math.hypot(o, o) / 2 - distance))
        diag = next(((o, o) for o in candidates if sum(1 for b in BOUNDS if math.hypot(o, o) / 2 >= b) == expected), None)
        assert diag is not None, distance
        for name, (hx, hy) in (("axis", axis), ("diagonal", diag)):
            tiles = tiles_at(hx, hy)
            assert len(tiles) == (8 if name == "axis" else 4), (distance, name, tiles)
            for x, y in tiles:
                ring = ring_exact(x, y)
                assert ring == expected == ring_float(x + 0.5, y + 0.5), (distance, name, x, y, ring)
                rings.append({"tile": [x, y], "ring": ring, "distance": distance, "direction": name})
    points = []
    for px, py in [(10.0, 10.0), (89.9, 10.0), (90.0, 10.0), (10.0, -70.0), (-60.0, -60.0), (710.0, 10.0), (10.25, 709.75)]:
        points.append({"point": [px, py], "ring": ring_float(px, py)})
    return {"cell_tiles": CELL, "bounds": BOUNDS, "division": div, "rings": rings, "points": points}


def render_h(data):
    lines = ["#pragma once",
             "// Generated by tools/build/gen_coords_vectors.py. Do not edit. Same values as coords_vectors.json.",
             "", "#include <cstdint>", "#include <vector>", "", "namespace golden_coords {", "",
             "struct Division { int64_t tile, cell, local; };",
             "struct Ring { int64_t x, y, ring; };",
             "struct Point { double x, y; int64_t ring; };", "",
             "inline const std::vector<int64_t> BOUNDS = {" + ", ".join(map(str, data["bounds"])) + "};",
             "inline const std::vector<Division> DIVISION = {"]
    lines += [f"\t{{{d['tile']}, {d['cell']}, {d['local']}}}," for d in data["division"]]
    lines += ["};", "inline const std::vector<Ring> RINGS = {"]
    lines += [f"\t{{{r['tile'][0]}, {r['tile'][1]}, {r['ring']}}}," for r in data["rings"]]
    lines += ["};", "inline const std::vector<Point> POINTS = {"]
    lines += [f"\t{{{p['point'][0]!r}, {p['point'][1]!r}, {p['ring']}}}," for p in data["points"]]
    lines += ["};", "", "} // namespace golden_coords", ""]
    return "\n".join(lines)


def main():
    data = build()
    outputs = {OUT_JSON: json.dumps(data, indent="\t") + "\n", OUT_H: render_h(data)}
    if "--check" in sys.argv:
        stale = [str(p) for p, t in outputs.items() if not p.exists() or p.read_text() != t]
        if stale:
            print("gen_coords_vectors: stale: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("gen_coords_vectors: up to date")
        return 0
    for p, t in outputs.items():
        p.write_text(t)
    print(f"gen_coords_vectors: {len(data['rings'])} ring cases, {len(data['division'])} division cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
