#!/usr/bin/env python3
"""Writes native/tests/golden/rng_golden.json and rng_golden.gen.h from rng_reference.py (FND-06).

The C++ (doctest) and GDScript (GUT) tests both reproduce every entry. 64-bit values are
hex strings of their bit pattern ("0x" + 16 digits), since JSON numbers are doubles.
Usage: python3 tools/build/gen_rng_golden.py [--check]
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rng_reference import G, Rng, hash_u64, i64, mix64, sub_seed, u64  # noqa: E402

GAME = Path(__file__).resolve().parents[2]
OUT_JSON = GAME / "native/tests/golden/rng_golden.json"
OUT_H = GAME / "native/tests/golden/rng_golden.gen.h"
I64_MIN, I64_MAX = -(1 << 63), (1 << 63) - 1


def hx(x):
    return "0x%016x" % u64(x)


def build():
    seq = Rng(0xC0FFEE)
    mix_inputs = [0, 1, 2, 3, 1 << 63, (1 << 64) - 1, (1 << 63) - 1, G, 0xFFFFFFFF, 1 << 32]
    while len(mix_inputs) < 64:
        mix_inputs.append(seq.next())
    data = {"version": 1, "mix64": [[hx(x), hx(mix64(x))] for x in mix_inputs]}

    hashes = []
    special_keys = [[], [0], [-1], [I64_MIN], [I64_MAX], [1, 2, 3], [-5, 7, -9, 11],
                    [0, 0, 0, 0, 0, 0], [123456789, -987654321], [-1, -1]]
    for i in range(100):
        seed = seq.next() if i % 3 else i
        domain = i % 13
        keys = special_keys[i] if i < len(special_keys) else [i64(seq.next()) >> (i % 40) for _ in range(i % 5)]
        hashes.append({"seed": hx(seed), "domain": domain, "keys": [hx(k) for k in keys],
                       "hash": hx(hash_u64(seed, domain, keys))})
    data["hash_u64"] = hashes

    data["sub_seed"] = []
    for attempt in range(0, 22, 3):
        keys = [17, -42]
        data["sub_seed"].append({"seed": hx(99), "domain": 4, "keys": [hx(k) for k in keys],
                                 "attempt": attempt, "value": hx(sub_seed(99, 4, keys, attempt))})

    stream_seeds = [0, 1, 1234567, 42, (1 << 64) - 1, 1 << 63, G, 0xDEADBEEFCAFEBABE]
    streams = []
    for s in stream_seeds:
        r = Rng(s)
        streams.append({"seed": hx(s), "outputs": [hx(r.next()) for _ in range(32)]})
    data["streams"] = streams

    ranges = []
    for s, lo, hi in [(1, 5, 5), (2, 0, 9), (3, -10, 10), (4, I64_MIN, I64_MAX), (5, 0, (1 << 62)),
                      (6, -(1 << 40), 1 << 40), (7, 0, 1), (8, I64_MIN, I64_MIN + 2), (9, I64_MAX - 3, I64_MAX),
                      (10, 0, 999999), (11, 0, (1 << 63) + 0 - 1), (12, -3, -1)]:
        r = Rng(s)
        ranges.append({"seed": hx(s), "lo": hx(lo), "hi": hx(hi), "draws": [hx(r.range(lo, hi)) for _ in range(16)]})
    data["range"] = ranges

    chances = []
    for s, p in [(1, 0), (2, 1000000), (3, 500000), (4, 1), (5, 999999), (6, 250000)]:
        r = Rng(s)
        chances.append({"seed": hx(s), "ppm": p, "results": [1 if r.chance_ppm(p) else 0 for _ in range(32)]})
    data["chance_ppm"] = chances

    picks = []
    for s, w in [(1, [1, 1, 1]), (2, [0, 5, 0, 5]), (3, [100]), (4, [1, 0, 1000000]), (5, [3, 1, 4, 1, 5, 9, 2, 6]),
                 (6, [0, 0, 1])]:
        r = Rng(s)
        picks.append({"seed": hx(s), "weights": w, "picks": [r.pick_weighted(w) for _ in range(32)]})
    data["pick_weighted"] = picks

    shuffles = []
    for s, n in [(1, 1), (2, 2), (3, 5), (4, 10), (5, 52)]:
        r = Rng(s)
        shuffles.append({"seed": hx(s), "n": n, "result": r.shuffle(list(range(n)))})
    data["shuffle"] = shuffles

    units = []
    for s in [0, 1, 77]:
        r = Rng(s)
        units.append({"seed": hx(s), "raw53": [hx(r.unit_raw53()) for _ in range(8)]})
    data["unit_double"] = units
    return data


def render_h(data):
    def u(x):
        return x + "ULL"

    lines = ["#pragma once",
             "// Generated by tools/build/gen_rng_golden.py from rng_reference.py. Do not edit.",
             "// The same values as rng_golden.json, for the doctest runner.",
             "",
             "#include <cstdint>",
             "#include <vector>",
             "",
             "namespace golden {",
             "",
             "struct Mix { uint64_t in, out; };",
             "struct Hash { uint64_t seed, domain; std::vector<uint64_t> keys; uint64_t hash; };",
             "struct SubSeed { uint64_t seed, domain; std::vector<uint64_t> keys; int64_t attempt; uint64_t value; };",
             "struct Stream { uint64_t seed; std::vector<uint64_t> outputs; };",
             "struct Range { uint64_t seed, lo, hi; std::vector<uint64_t> draws; };",
             "struct Chance { uint64_t seed; int64_t ppm; std::vector<int> results; };",
             "struct Pick { uint64_t seed; std::vector<int64_t> weights; std::vector<int64_t> picks; };",
             "struct Shuffle { uint64_t seed; int64_t n; std::vector<int64_t> result; };",
             "struct Unit { uint64_t seed; std::vector<uint64_t> raw53; };",
             ""]
    lines.append("inline const std::vector<Mix> MIX = {")
    lines += [f"\t{{{u(a)}, {u(b)}}}," for a, b in data["mix64"]]
    lines.append("};")
    lines.append("inline const std::vector<Hash> HASH = {")
    lines += [f"\t{{{u(h['seed'])}, {h['domain']}, {{{', '.join(u(k) for k in h['keys'])}}}, {u(h['hash'])}}}," for h in data["hash_u64"]]
    lines.append("};")
    lines.append("inline const std::vector<SubSeed> SUB_SEED = {")
    lines += [f"\t{{{u(h['seed'])}, {h['domain']}, {{{', '.join(u(k) for k in h['keys'])}}}, {h['attempt']}, {u(h['value'])}}}," for h in data["sub_seed"]]
    lines.append("};")
    lines.append("inline const std::vector<Stream> STREAMS = {")
    lines += [f"\t{{{u(s['seed'])}, {{{', '.join(u(x) for x in s['outputs'])}}}}}," for s in data["streams"]]
    lines.append("};")
    lines.append("inline const std::vector<Range> RANGES = {")
    lines += [f"\t{{{u(r['seed'])}, {u(r['lo'])}, {u(r['hi'])}, {{{', '.join(u(x) for x in r['draws'])}}}}}," for r in data["range"]]
    lines.append("};")
    lines.append("inline const std::vector<Chance> CHANCES = {")
    lines += [f"\t{{{u(c['seed'])}, {c['ppm']}, {{{', '.join(str(x) for x in c['results'])}}}}}," for c in data["chance_ppm"]]
    lines.append("};")
    lines.append("inline const std::vector<Pick> PICKS = {")
    lines += [f"\t{{{u(p['seed'])}, {{{', '.join(str(x) for x in p['weights'])}}}, {{{', '.join(str(x) for x in p['picks'])}}}}}," for p in data["pick_weighted"]]
    lines.append("};")
    lines.append("inline const std::vector<Shuffle> SHUFFLES = {")
    lines += [f"\t{{{u(s['seed'])}, {s['n']}, {{{', '.join(str(x) for x in s['result'])}}}}}," for s in data["shuffle"]]
    lines.append("};")
    lines.append("inline const std::vector<Unit> UNITS = {")
    lines += [f"\t{{{u(s['seed'])}, {{{', '.join(u(x) for x in s['raw53'])}}}}}," for s in data["unit_double"]]
    lines.append("};")
    lines += ["", "} // namespace golden", ""]
    return "\n".join(lines)


def main():
    data = build()
    outputs = {OUT_JSON: json.dumps(data, indent="\t") + "\n", OUT_H: render_h(data)}
    if "--check" in sys.argv:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("gen_rng_golden: stale: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("gen_rng_golden: up to date")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"gen_rng_golden: wrote {OUT_JSON.name} and {OUT_H.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
